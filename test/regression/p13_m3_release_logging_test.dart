// Phase 13 / M3 Stage 1 remediation (N-1): release builds must not log
// package names, pending-challenge details or security-state identifiers
// from native code.
//
// Static source invariants (host test; real release logcat is device QA):
//  RL-01 android.util.Log / println / printStackTrace / System.out|err are
//        used only by DiagLog.kt in native sources.
//  RL-02 every DiagLog emitter returns before logging unless the app is
//        debuggable (ApplicationInfo.FLAG_DEBUGGABLE, fail closed).
//  RL-03 every DiagLog call passes a lazy, side-effect-free message lambda.
//  RL-04 the release build type is never debuggable.
//  RL-05 the SAL_QA_DIAG Dart diagnostics define is debug/profile-only by
//        default (absent from build scripts).
// ReleaseLogPolicy semantics are covered by the JVM test
// android/app/src/test/kotlin/com/smartapplock/app/ReleaseLogPolicyTest.kt.

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

const String _nativeRoot = 'android/app/src/main';
const String _diagLog =
    'android/app/src/main/kotlin/com/smartapplock/app/DiagLog.kt';

/// Flutter-tool output (git-ignored, regenerated by `pub get`); it logs only
/// plugin-registration failures (plugin class names, no app data) through
/// io.flutter.Log and cannot be edited. Excluded by exact path only.
const String _generatedRegistrant =
    'android/app/src/main/java/io/flutter/plugins/GeneratedPluginRegistrant.java';

List<File> _nativeSources() => Directory(_nativeRoot)
    .listSync(recursive: true)
    .whereType<File>()
    .where((File f) => f.path.endsWith('.kt') || f.path.endsWith('.java'))
    .where((File f) => _norm(f.path) != _generatedRegistrant)
    .toList()
  ..sort((File a, File b) => a.path.compareTo(b.path));

String _norm(String p) => p.replaceAll(r'\', '/');

/// Strips `//` line comments and `/* */` block comments (not inside strings
/// in practice for these sources) so documentation may mention the APIs.
String _code(String src) => src
    .replaceAll(RegExp(r'/\*[\s\S]*?\*/'), '')
    .split('\n')
    .map((String l) {
      final int i = l.indexOf('//');
      return i < 0 ? l : l.substring(0, i);
    })
    .join('\n');

/// Returns the text of the brace block starting at [open] (index of `{`).
String _block(String s, int open) {
  int depth = 0;
  for (int i = open; i < s.length; i++) {
    if (s[i] == '{') depth++;
    if (s[i] == '}') {
      depth--;
      if (depth == 0) return s.substring(open + 1, i);
    }
  }
  throw StateError('unbalanced block at $open');
}

/// Index of the `)` matching the `(` at [open].
int _closeParen(String s, int open) {
  int depth = 0;
  for (int i = open; i < s.length; i++) {
    if (s[i] == '(') depth++;
    if (s[i] == ')') {
      depth--;
      if (depth == 0) return i;
    }
  }
  throw StateError('unbalanced parens at $open');
}

void main() {
  test('RL-01 raw logging APIs appear only in DiagLog.kt', () {
    final RegExp banned = RegExp(
      r'\bandroid\.util\.Log\b|(?<![\w.])Log\.(v|d|i|w|e|wtf|println|isLoggable)\s*\(|'
      r'\bprintln\s*\(|\bprint\s*\(|printStackTrace\s*\(|System\.(out|err)\b|'
      r'\bTimber\b|\bjava\.util\.logging\b',
    );
    final List<String> hits = <String>[];
    final List<File> files = _nativeSources();
    expect(files.length, greaterThan(10), reason: 'native sources not found');
    for (final File f in files) {
      if (_norm(f.path) == _diagLog) continue;
      final List<String> lines = _code(f.readAsStringSync()).split('\n');
      for (int i = 0; i < lines.length; i++) {
        if (banned.hasMatch(lines[i])) hits.add('${_norm(f.path)}:${i + 1}');
      }
    }
    expect(hits, isEmpty, reason: hits.join('\n'));
  });

  test('RL-02 every DiagLog emitter is gated on FLAG_DEBUGGABLE, fail closed',
      () {
    final String src = _code(File(_diagLog).readAsStringSync());
    // The gate reads the real platform constant and fails closed.
    final RegExp enabled = RegExp(r'fun enabled\(context: Context\): Boolean');
    final Match? em = enabled.firstMatch(src);
    expect(em, isNotNull);
    final String gate = src.substring(em!.end, src.indexOf('fun d('));
    expect(gate, contains('ReleaseLogPolicy.allows('));
    expect(gate, contains('ApplicationInfo.FLAG_DEBUGGABLE'));
    expect(RegExp(r'catch\s*\([^)]*\)\s*\{\s*false\s*\}').hasMatch(gate),
        isTrue,
        reason: 'flag read failure must disable logging');
    expect(gate.contains('true'), isFalse, reason: 'no hard-coded enable');

    // Every function that logs returns first unless enabled.
    final RegExp fn = RegExp(r'\bfun (\w+)\s*\(');
    int emitters = 0;
    for (final Match m in fn.allMatches(src)) {
      final int open = src.indexOf('{', _closeParen(src, m.end - 1));
      final String body = _block(src, open);
      if (!RegExp(r'\bLog\.').hasMatch(body)) continue;
      emitters++;
      final String first = body.trimLeft();
      expect(first.startsWith('if (!enabled(context)) return'), isTrue,
          reason: 'DiagLog.${m.group(1)} must gate before logging');
      // The message is a lambda evaluated only after the gate.
      final String sig = src.substring(m.end, _closeParen(src, m.end - 1));
      expect(sig, contains('message: () -> String'),
          reason: 'DiagLog.${m.group(1)} must take a lazy message');
      expect(body.split('if (!enabled(context)) return').first.trim(), isEmpty);
    }
    expect(emitters, 2, reason: 'expected exactly DiagLog.d and DiagLog.w');
    // Nothing else in the object references Log outside the emitters.
    expect(RegExp(r'\bLog\.(v|i|e|wtf|println)\b').hasMatch(src), isFalse);
  });

  test('RL-03 DiagLog call sites pass lazy, side-effect-free message lambdas',
      () {
    final RegExp call = RegExp(r'\bDiagLog\.(d|w)\s*\(');
    int sites = 0;
    final List<String> bad = <String>[];
    for (final File f in _nativeSources()) {
      if (_norm(f.path) == _diagLog) continue;
      final String src = _code(f.readAsStringSync());
      for (final Match m in call.allMatches(src)) {
        sites++;
        final int close = _closeParen(src, m.end - 1);
        final String after = src.substring(close + 1).trimLeft();
        final String where =
            '${_norm(f.path)}:${src.substring(0, m.start).split('\n').length}';
        if (!after.startsWith('{')) {
          bad.add('$where: message must be a trailing lambda');
          continue;
        }
        final String body = _block(src, src.indexOf('{', close)).trim();
        // A message is a string expression only: no calls, no assignment,
        // no increments (behaviour must not depend on logging).
        final bool stringOnly = body.startsWith('"') &&
            !body.contains('(') &&
            !RegExp(r'(^|[^=!<>])=([^=]|$)').hasMatch(
                body.replaceAll(RegExp(r'"(?:[^"\\]|\\.)*"'), '""')) &&
            !body.contains('++') &&
            !body.contains('--');
        if (!stringOnly) bad.add('$where: message lambda must be string-only');
      }
    }
    expect(bad, isEmpty, reason: bad.join('\n'));
    // Count pinned so a removed site or a new raw site is noticed in review.
    expect(sites, 20);
  });

  test('RL-04 the release build type is never debuggable', () {
    final String gradle = _code(
        File('android/app/build.gradle.kts').readAsStringSync());
    expect(RegExp(r'isDebuggable\s*=\s*true').hasMatch(gradle), isFalse);
    expect(RegExp(r'debuggable\s*\(?\s*true').hasMatch(gradle), isFalse);
    final String manifest =
        File('$_nativeRoot/AndroidManifest.xml').readAsStringSync();
    expect(manifest.contains('android:debuggable'), isFalse);
  });

  test('RL-05 SAL_QA_DIAG is not enabled by any build script', () {
    for (final String p in <String>[
      'android/app/build.gradle.kts',
      'android/build.gradle.kts',
      'android/gradle.properties',
    ]) {
      final File f = File(p);
      if (!f.existsSync()) continue;
      expect(f.readAsStringSync().contains('SAL_QA_DIAG'), isFalse,
          reason: '$p must not set the diagnostics define');
    }
  });
}
